static inline uint32_t host_crc32_advance_1024(uint32_t crc)
{
    return host_crc32_shift_1024[0][crc & 255U] ^
           host_crc32_shift_1024[1][(crc >> 8) & 255U] ^
           host_crc32_shift_1024[2][(crc >> 16) & 255U] ^
           host_crc32_shift_1024[3][crc >> 24];
}

static inline uint32_t host_crc32_page(const void *buffer)
{
    const uint8_t *bytes = buffer;
    uint32_t a = 0xffffffffU, b = 0, c = 0, d = 0;
    for (unsigned offset = 0; offset < 1024; offset += 8)
    {
        uint64_t wa, wb, wc, wd;
        /* memcpy permits unaligned input without strict-aliasing violations. */
        memcpy(&wa, bytes + offset, sizeof(wa));
        memcpy(&wb, bytes + 1024 + offset, sizeof(wb));
        memcpy(&wc, bytes + 2048 + offset, sizeof(wc));
        memcpy(&wd, bytes + 3072 + offset, sizeof(wd));
        a = __builtin_aarch64_crc32x(a, wa);
        b = __builtin_aarch64_crc32x(b, wb);
        c = __builtin_aarch64_crc32x(c, wc);
        d = __builtin_aarch64_crc32x(d, wd);
    }
    a = host_crc32_advance_1024(a) ^ b;
    a = host_crc32_advance_1024(a) ^ c;
    a = host_crc32_advance_1024(a) ^ d;
    return a ^ 0xffffffffU;
}
